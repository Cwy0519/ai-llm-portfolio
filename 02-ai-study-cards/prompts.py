"""提示词模板 + 卡片类型定义：整个项目的"大脑"其实就在这里。

提示词的四个要素（答辩可以直接背）：
    1. 角色——你希望模型以什么身份工作（很会做学习资料的老师）
    2. 任务——具体做什么、做多少（生成几张、什么难度、针对哪段材料）
    3. 约束——不许做什么（不许编造、不许输出解释、只许输出 JSON）
    4. 输出格式——严格的 JSON 结构（程序要能解析）

为什么单独放一个文件？
    调提示词是整个项目里最高频的操作，改这里不用碰界面和网络代码。

五种卡片不是"写五个生成函数"，而是"同一套 JSON 协议 + 五种写作规则"。
所以以后想加第六种卡片，只要在 CARD_TYPES 里加一项、写一段 rules，
界面会自动多出一个 Tab，业务代码一行都不用改。

本文件用到的 Python 知识（答辩时随便指一处，先报名字再解释）：
    1. @dataclass(frozen=True)       —— 不可变的数据类，字段建好就不能改
    2. 类型提示 dict[str, CardType]   —— 声明字典"键、值"分别是什么类型
    3. 关键字参数                     —— CardType(key=..., label=...) 按名字传参
    4. 圆括号内相邻字符串的隐式拼接     —— 分几行写，拼起来仍是一个字符串
    5. 三引号多行字符串 '''...'''     —— OUTPUT_SCHEMA 这种带换行的长文本
    6. 函数默认参数                   —— level: str = "进阶"
    7. dict.get(键, 默认值)           —— 取不到不报错，改用默认值
    8. f-string                       —— 字符串里嵌变量或属性
    9. 模块级常量（全大写命名）        —— 全大写是"约定"，不是语法强制
    10. 提前 return / if 分支          —— 让函数流程读起来像人话
"""

# 【from ... import ...】这里只需要 dataclass 这一个装饰器
from dataclasses import dataclass


# 【装饰器 + 参数】@dataclass(frozen=True) = "数据类 + 冻结"。
#   frozen=True 的含义：对象一旦创建，字段就不能再改，改了就抛 FrozenInstanceError。
#   为什么要冻结？卡片类型是全项目共用的"配置数据"，冻结能防止某处代码手滑改掉它。
#   打个比方：它不是草稿纸，而是印刷好的说明书，只能读、不能改。
@dataclass(frozen=True)
class CardType:
    """一种卡片的"说明书"：叫什么、怎么渲染、让模型怎么写。"""

    # 【类型提示 + 字段】每一行 = dataclass 自动生成的一个字段（也是 __init__ 的参数）。
    #   注意：自动生成的 __init__ 按"这里写的顺序"接收参数，所以顺序有意义。
    key: str            # 程序内部用的短名，英文小写
    label: str          # 界面上显示的名字
    emoji: str
    intro: str          # 界面提示：这类卡片适合什么场景
