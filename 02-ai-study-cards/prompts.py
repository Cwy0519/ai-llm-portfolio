# 界面上的难度选项。难度不是玄学，就是给模型的一段额外要求。
# 【list[str] 类型提示】列表里装字符串；这里顺便决定了界面上单选项的顺序。
LEVELS: list[str] = ["入门", "进阶", "挑战"]

# 【模块级常量】全大写命名是"约定"（不是语法强制），表示"这段程序别去改它"。
#   字典的键必须和 LEVELS 里的字符串一模一样，否则 .get() 会取不到。
LEVEL_RULES: dict[str, str] = {
    "入门": "面向刚接触这个知识点的同学：只考概念和定义，语言直白，不要绕弯子。",
    "进阶": "面向已经学过一遍的同学：考理解、辨析和简单应用，可以有易混概念的对比。",
    "挑战": "面向准备考试的同学：考综合运用、常见陷阱和知识之间的联系，可以适度加大难度。",
}


# 【圆括号续行 + 隐式拼接】system 提示词：只写一次、所有卡片共用。
#   相邻字符串自动拼接，"…\n" 里的 \n 才是真正的换行，写的时候别丢掉。
SYSTEM_PROMPT = (
    "你是一位很会做学习资料的老师，擅长把一段学习材料拆成多种形式的复习卡片。\n"
    "你的输出会直接显示在网页上，所以必须严格遵守：\n"
    "1. 只输出一个 JSON 对象，不要输出 Markdown 代码块（不要 ```json），"
    "不要任何解释、前言或结尾的话。\n"
    "2. 所有内容用简体中文。\n"
    "3. 只使用学习材料里出现的信息，不要编造材料里没有的事实、数字或结论。\n"
    "4. 严格按给定的 JSON 结构输出，字段名一个都不能改。"
)

# 统一的 JSON 协议：五种卡片共用，所以界面只写一套渲染逻辑。
# 【三引号多行字符串】三引号字符串会原样保留换行和缩进，
#   所以这段 JSON 晒出来就是"能直接照着填"的样子，比压成一行好懂得多。
#   注意：这里必须保持"纯 JSON 文本"，不能在字符串内部加 # 注释，否则会破坏 JSON。
OUTPUT_SCHEMA = """{
  "title": "这份材料的主题（不超过 20 字）",
  "summary": "一句话总结材料在讲什么（不超过 60 字）",
  "items": [
    {
      "front": "卡片正面内容（问题 / 题干 / 要点 / 概念）",
      "back": "卡片背面内容（答案 / 解释 / 口诀）",
      "tip": "可选的一句记忆提示；没有就填空字符串"
    }
  ]
}"""


# 【def 多行签名 + 默认参数】前两个参数 text / card 必须传；
#   后面四个写成 "名字: 类型 = 默认值"，叫"默认参数"：不传就用默认值。
#   语法规定：默认参数必须排在必传参数后面，否则直接语法错误。
def build_messages(
    text: str,
    card: CardType,
    # 【默认参数】不指定难度就是"进阶"，不指定数量就出 4 张
    level: str = "进阶",
    count: int = 4,
    # 【默认参数】分段信息默认 1/1，表示"只有一段"，也就是材料没被切分
    part_index: int = 1,
    part_total: int = 1,
) -> list[dict]:
    """把"材料 + 卡片类型 + 难度 + 数量"套进提示词模板。

    返回 OpenAI 格式的消息列表：先 system（设定身份和规则），再 user（具体任务）。
    这个格式所有兼容 OpenAI 接口的平台都认，换平台不用改这里。
    """
    # 【dict.get(键, 默认值)】按难度名取规则；万一传了个不认识的难度，
    #   就退回"进阶"的规则，而不是抛 KeyError 把程序搞崩。
    level_rule = LEVEL_RULES.get(level, LEVEL_RULES["进阶"])

    # 【变量初始化】先给空字符串，下面按条件决定要不要往里填内容。
    # 材料很长时会被切成多段，这里告诉模型"你只负责这一段"。
    part_hint = ""
    # 【if + 数值比较】只有真的分成多段（> 1）才需要这句提示，单段时是废话
    if part_total > 1:
        # 【f-string 与普通字符串混拼】带 f 的那段会替换 {变量}，
        #   不带 f 的那段原样保留；相邻字符串照样自动拼成一个整体。
        part_hint = (
            f"\n注意：这是较长材料的第 {part_index}/{part_total} 段，"
            "只针对这一段出卡片，不要重复其它段落的内容。\n"
        )

    # 【f-string 多行拼接】整段提示词由多段字符串拼成，每段末尾的 \n 控制换行；
    #   外面的圆括号让它可以换行写，最终仍然只是"一个字符串"。
    user = (
        f"请根据下面的学习材料，生成 {count} 张「{card.label}」。\n\n"
        # 【属性访问】card 是 CardType 对象，用"点"取出它的 label 字段
        f"【难度要求】{level}：{level_rule}\n\n"
        f"【这一类卡片的写法要求】{card.rules}\n\n"
        # 【把常量插进提示词】OUTPUT_SCHEMA 就是上面那段 JSON 文本
        f"【输出格式】严格返回下面结构的 JSON：\n{OUTPUT_SCHEMA}\n\n"
        f"【正面/背面示例】\n"
        f"front: {card.example_front}\n"
        f"back: {card.example_back}\n\n"
        # 【插入普通变量】part_hint 也可能是空字符串，空串拼进去等于没加
        f"{part_hint}"
        f"【学习材料】\n{text}\n\n"
        # 【收尾催促】最后再强调一次"只输出 JSON"，减少模型加废话的概率
        f"现在请直接输出 JSON（共 {count} 张卡）："
    )
    # 【返回 list[dict]】OpenAI 接口要求 messages 是"消息列表"：
    #   第 1 条 role=system 定身份和总规则，第 2 条 role=user 给本次具体任务。
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user},
    ]
