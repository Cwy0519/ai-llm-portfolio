"""间隔复习计划：纯本地计算，不花一次模型调用。

依据是艾宾浩斯遗忘曲线的常见简化版：
    学完当天过一遍，之后在第 1、2、4、7、15 天各复习一次。
    复习间隔逐渐拉长，用最少的次数对抗遗忘。

为什么用代码算而不是让模型算？
    日期计算是确定性的事，代码算得又快又准；
    只有"创作"类任务（写卡片、编口诀）才值得花一次模型调用。
    这也是答辩可以讲的一个小设计取舍。

本文件用到的 Python 知识（答辩时指着某一行，先报名字再解释）：
    1.  from datetime import date, timedelta —— 只导入日期类和时间间隔类
    2.  date.today()                        —— 取"今天"这个日期
    3.  timedelta(days=7)                   —— 表示"7 天"这个时间间隔
    4.  date + timedelta                    —— 日期加间隔 = 往后推几天
    5.  date.weekday()                      —— 星期几，返回 0(周一) ~ 6(周日)
    6.  字符串下标 _WEEKDAY[0]                —— 用数字取字符串里的第几个字
    7.  dict 用整数当键 {1: "..."}            —— 键不一定是字符串
    8.  enumerate(列表, 1)                  —— 同时拿序号（从 1 开始）和元素
    9.  f-string 日期格式化 {day:%Y-%m-%d}   —— 在 {} 里直接用格式说明符
    10. X | None 联合类型 + 默认参数          —— "可以不传，默认 None"
    11. or 兜底 a or b                       —— 左边是假值就用右边
    12. 字符串 += 累加 / 括号续行 + 隐式拼接  —— 把长文案拼起来
    13. 关键字参数 days=gap                  —— 参数名写清楚，避免传错位置
"""

# 【from ... import ...】从 datetime 模块导入两个类：
#   date      —— 只表示"年月日"，不带时分秒
#   timedelta —— 表示"一段时间间隔"，比如 7 天、3 小时
from datetime import date, timedelta

# 【list + 整数】复习间隔：学完之后第 1、2、4、7、15 天各复习一次
#   间隔越来越大，是因为遗忘速度"先快后慢"，前面多复习几次最划算
INTERVALS = [1, 2, 4, 7, 15]

# 【dict 字典 + 整数键】键是"距今天第几天"，值是"这一轮具体做什么"
#   这里用整数当键，是因为下面可以直接 TASKS[gap] 取值，不用转字符串
TASKS = {
    # 【键值对】键 1，值是一句复习建议
    1: "趁热打铁：把问答卡过一遍，答错的先标出来",
    # 【键值对】键 2
    2: "遮住答案自测：重点看昨天标错的题",
    # 【键值对】键 4
    4: "写一遍填空题，再默写记忆口诀",
    # 【键值对】键 7
    7: "用「类比解释」把概念讲给同学听，讲不通的地方回看材料",
    # 【键值对】键 15
    15: "整体自测：随机抽 5 张卡，能答上 4 张就算过关",
}

# 【字符串当查表用】"一二三四五六日" 共 7 个字符，下标 0~6 正好对应周一到周日
#   为什么要这张表？因为 date.weekday() 返回的是数字，人看着不直观
_WEEKDAY = "一二三四五六日"


# 【def 函数 + 全部带默认值】调用时不传参数也能生成一份"今天开始"的计划
def build_plan(
    # 【参数默认值】n_items=0：这次生成了多少张卡（只用来写进总结那句）
    n_items: int = 0,
    # 【参数默认值】n_types=0：生成了几种形式
    n_types: int = 0,
    # 【参数默认值】level="进阶"：难度，写进标题
    level: str = "进阶",
    # 【联合类型 + 默认值】today 可以是 date，也可以是 None（默认今天）
    #   留这个参数是为了测试：传一个固定日期，输出就可复现、能写单元测试
    today: date | None = None,
# 【返回值类型】返回一段 Markdown 文本
) -> str:
    """生成一份 Markdown 复习计划表。

    参数：
        n_items  这次一共生成了多少张卡
        n_types  生成了几种形式
        level    难度
        today    起始日期（默认今天；测试时可以传固定日期）
    """
    # 【or 兜底】today 是 None 时用 date.today() 取今天
    #   注意：or 判断的是"真假值"，date 对象永远是"真"，所以传了就用传的
    today = today or date.today()

    # 【list 列表字面量】先把 Markdown 表格的"表头"和"对齐分隔行"放进列表
    #   Markdown 表格的规则：第一行是表头，第二行用 |---| 声明每列对齐方式
    rows = [
        "| 轮次 | 日期 | 距今天 | 复习内容 |",
        "|---|---|---|---|",
    ]
    # 【for + enumerate】从 1 开始编号：i 是"第几轮"，gap 是"隔几天"
    #   enumerate 同时给出下标和元素，比写 for k in range(len(...)) 更清楚
    for i, gap in enumerate(INTERVALS, 1):
        # 【date + timedelta】日期对象加时间间隔，得到"往后推 gap 天"的新日期
        #   关键字参数 days=gap 写明单位是"天"，比 positional 传参更不容易错
        day = today + timedelta(days=gap)
        # 【方法调用 + 字符串下标】day.weekday() 返回 0(周一)~6(周日)；
        #   用它当下标去 _WEEKDAY 里取一个汉字，比如 0 → "一"
        weekday = _WEEKDAY[day.weekday()]
        # 【append + f-string】往列表末尾追加一行表格
        #   每个 | 分隔一个单元格；{day:%Y-%m-%d} 把日期格式化成 2026-10-25 这样
        rows.append(
            f"| 第 {i} 轮 | {day:%Y-%m-%d}（周{weekday}） | {gap} 天后 | {TASKS[gap]} |"
        )

    # 【f-string + 加粗】** 是 Markdown 的加粗语法，这里把数字加粗更显眼
    summary = f"本次共生成 **{n_items}** 张卡"
    # 【if 真值判断】n_types 是 0 就不写"几种形式"，避免出现"（0 种形式）"
    if n_types:
        # 【+= 累加】等价于 summary = summary + ...；注意字符串是不可变对象，
        #   每次 += 其实都造了一个新字符串（数据量小时完全不用在意）
        summary += f"（{n_types} 种形式）"

    # 【return 括号续行】圆括号把多行表达式括起来，就可以随便换行
    return (
        # 【隐式字符串拼接】相邻的两个字符串字面量会自动接成一段（不用写 +）
        f"### 📅 间隔复习计划（{level}）\n\n"
        f"> {summary}。计划从今天开始，共 5 轮：\n\n"
        # 【显式 + 拼接】"\n".join(rows) 把表格的每一行用换行连起来
        #   注意优先级：相邻字符串先拼成一段，再和 + 连起来的其它部分相加
        + "\n".join(rows)
        # 【+ 拼接】表格后面接一句提醒；这里两个相邻字符串又自动拼成一段
        + "\n\n💡 把日期加进手机日历更不容易忘。"
        "复习顺序建议：问答卡/填空题自测 → 口诀回忆 → 类比讲解检验理解。\n"
    )
